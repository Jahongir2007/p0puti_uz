// Generates the dark-mode colour overrides in src/index.css from the colour classes the code uses.
// Run after adding new colours:  node scripts/build-dark-theme.mjs
//
// How dark mode works: the grey scale (slate) is redefined as CSS variables under `.dark`,
// so every bg-/text-/ring-slate-* class follows automatically. White and the light accent
// tints can't be flipped the same way (white is also the text colour on blue buttons), so
// each class that uses them gets an explicit `.dark` override, generated here.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSS = path.join(root, "src/index.css");
const START = "/* --- dark theme overrides: generated by scripts/build-dark-theme.mjs, do not edit --- */";
const END = "/* --- end of generated dark theme overrides --- */";

const SURFACE = "#151e2e"; // cards (bg-white in light mode)
const ACCENTS = ["sky", "emerald", "amber", "rose", "red", "violet"];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : /\.(jsx?|tsx?)$/.test(e.name) ? [path.join(dir, e.name)] : []
  );
}
const source = walk(path.join(root, "src")).map((f) => fs.readFileSync(f, "utf8")).join("\n");
const classRe = /(?<![\w-])((?:[a-z-]+:)*)(bg|ring|border|text)-(white|sky|emerald|amber|rose|red|violet)(?:-(\d{2,3}))?(?:\/(\d+))?(?![\w-])/g;

const esc = (s) => s.replace(/([:/.[\]])/g, "\\$1");
const pseudo = { hover: ":hover", active: ":active", focus: ":focus", "focus-visible": ":focus-visible" };
const tint = (color, pct, alpha) => {
  const mix = `color-mix(in oklab, var(--color-${color}-500) ${pct}%, ${SURFACE})`;
  return alpha ? `color-mix(in oklab, ${mix} ${alpha}%, transparent)` : mix;
};

const rules = new Map();
for (const [, variants, prop, color, shade, alpha] of source.matchAll(classRe)) {
  const cls = `${variants}${prop}-${color}${shade ? "-" + shade : ""}${alpha ? "/" + alpha : ""}`;
  const vs = variants.split(":").filter(Boolean);
  if (vs.some((v) => !(v in pseudo))) continue; // peer-*/group-* variants only use mid shades
  const sel = `.dark .${esc(cls)}${vs.map((v) => pseudo[v]).join("")}`;
  const n = Number(shade);
  let decl = null;

  if (color === "white") {
    // white/10, white/15 are overlays on the blue hero: keep them. text-white stays white.
    if (prop === "bg" && (!alpha || Number(alpha) >= 50)) {
      decl = `background-color: ${alpha ? `color-mix(in oklab, ${SURFACE} ${alpha}%, transparent)` : SURFACE}`;
    } else if (prop === "ring" && !alpha) decl = `--tw-ring-color: ${SURFACE}`;
  } else if (ACCENTS.includes(color)) {
    if (prop === "bg" && n <= 100) decl = `background-color: ${tint(color, n === 50 ? 16 : 26, alpha)}`;
    else if (prop === "ring" && n <= 100) decl = `--tw-ring-color: ${tint(color, n === 50 ? 9 : 16, alpha)}`;
    else if (prop === "border" && n <= 200) decl = `border-color: ${tint(color, 30, alpha)}`;
    // dark accent text is hard to read on dark backgrounds: use the lighter shades
    else if (prop === "text" && n >= 600) decl = `color: var(--color-${color}-${n >= 800 ? 200 : n === 700 ? 300 : 400})`;
  }
  if (decl) rules.set(sel, decl);
}

const generated = [START, ...[...rules].sort().map(([s, d]) => `${s} { ${d}; }`), END].join("\n");
let css = fs.readFileSync(CSS, "utf8");
css = css.includes(START)
  ? css.slice(0, css.indexOf(START)) + generated + css.slice(css.indexOf(END) + END.length)
  : css.trimEnd() + "\n\n" + generated + "\n";
fs.writeFileSync(CSS, css);
console.log(`✅ ${rules.size} dark overrides written to src/index.css`);
